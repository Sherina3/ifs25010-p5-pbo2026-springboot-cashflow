package org.delcom.ifs25010springbootcashflow.adapter.repository;

import javax.sql.DataSource;

/** Membuat tabel users dan transactions bila belum ada (CREATE TABLE IF NOT EXISTS). */
public final class SchemaInitializer {
    private static final String CREATE_USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                full_name VARCHAR(200) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500)
            )""";

    private static final String CREATE_TRANSACTIONS = """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
            )""";

    private SchemaInitializer() {
    }

    public static void initialize(DataSource dataSource) {
        JdbcExecutor executor = new JdbcExecutor(dataSource);
        executor.execute(CREATE_USERS);
        executor.execute(CREATE_TRANSACTIONS);
    }
}
