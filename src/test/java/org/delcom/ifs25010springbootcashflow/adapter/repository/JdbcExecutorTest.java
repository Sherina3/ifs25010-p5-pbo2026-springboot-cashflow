package org.delcom.ifs25010springbootcashflow.adapter.repository;

import org.junit.jupiter.api.Test;

import javax.sql.DataSource;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class JdbcExecutorTest {

    @Test
    void executesDdlInsertQueryAndUpdate() {
        JdbcExecutor executor = new JdbcExecutor(JdbcSupportForTests.newH2());
        executor.execute("CREATE TABLE item (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(20))");

        int first = executor.insert("INSERT INTO item (name) VALUES (?)", statement -> statement.setString(1, "a"));
        int second = executor.insert("INSERT INTO item (name) VALUES (?)", statement -> statement.setString(1, "b"));
        assertEquals(1, first);
        assertEquals(2, second);

        List<String> names = executor.query("SELECT name FROM item ORDER BY id", statement -> { },
                resultSet -> resultSet.getString("name"));
        assertEquals(List.of("a", "b"), names);

        int changed = executor.update("UPDATE item SET name = ? WHERE id = ?", statement -> {
            statement.setString(1, "z");
            statement.setInt(2, 1);
        });
        assertEquals(1, changed);
    }

    @Test
    void translatesSqlFailuresToIllegalState() {
        DataSource failing = JdbcSupportForTests.failing();
        JdbcExecutor executor = new JdbcExecutor(failing);

        assertThrows(IllegalStateException.class, () -> executor.execute("SELECT 1"));
        assertThrows(IllegalStateException.class, () -> executor.update("DELETE FROM x", statement -> { }));
        assertThrows(IllegalStateException.class, () -> executor.insert("INSERT INTO x VALUES (1)", statement -> { }));
        assertThrows(IllegalStateException.class,
                () -> executor.query("SELECT 1", statement -> { }, resultSet -> resultSet.getInt(1)));
    }
}
